/**
 * Plan for `iw deploy` (pure). From [hosting] and the resources that already exist, decide what to create,
 * the exact wrangler commands and the generated wrangler.jsonc. No I/O (docs/spec/cli.md#iw-deploy).
 */
import type { HostingConfig, SigningKey } from '@indx-watch/bundle';

/** nodejs_compat is on by default from 2026-08-04; the flag is kept explicit (redundant flags are ignored). */
export const COMPATIBILITY_DATE = '2026-11-01';
export const WORKER_FIRST_ROUTES = ['/api/*', '/healthz', '/mcp', '/mcp/*', '/s/*'];
/** Placeholder for a D1 database that does not exist yet (only ever written by --dry-run). */
export const PENDING_ID = '<created by wrangler d1 create>';

export interface Existing {
  r2: string[];
  d1: { name: string; uuid: string }[];
  /** true when a Worker with this name is already deployed */
  worker?: boolean;
}

export interface PlanOptions {
  /** --name (overrides [hosting].name) */
  name?: string;
  public?: boolean;
  /** project.toml [[signing_keys]], pinned as the Worker's SIGNING_KEYS (docs/spec/security.md#signed-records) */
  signingKeys?: SigningKey[];
  /** Path of the generated wrangler.jsonc (appears in the deploy command) */
  configPath: string;
  /** Paths relative to the config file: the Worker bundle and the web build */
  main: string;
  assetsDir: string;
  compatibilityDate?: string;
}

export interface Resource {
  type: 'r2' | 'd1' | 'worker';
  name: string;
  exists: boolean;
}

export interface WranglerConfig {
  name: string;
  main: string;
  compatibility_date: string;
  compatibility_flags: string[];
  assets: {
    directory: string;
    binding: 'ASSETS';
    not_found_handling: 'single-page-application';
    run_worker_first: string[];
  };
  r2_buckets: { binding: 'STORE'; bucket_name: string }[];
  d1_databases: { binding: 'DB'; database_name: string; database_id: string }[];
  vars: Record<string, string>;
  triggers: { crons: string[] };
}

export interface DeployPlan {
  resources: Resource[];
  /** Arguments for wrangler, without the leading `wrangler` */
  steps: string[][];
  /** The same commands, shell-quoted for display */
  commands: string[];
  wranglerConfig: WranglerConfig;
}

export function resourceNames(hosting: HostingConfig, name?: string) {
  const worker = name ?? hosting.name;
  return { worker, bucket: hosting.r2_bucket ?? worker, database: hosting.d1_database ?? worker };
}

export function planDeploy(hosting: HostingConfig, existing: Existing, opts: PlanOptions): DeployPlan {
  const { worker, bucket, database } = resourceNames(hosting, opts.name);
  const db = existing.d1.find((d) => d.name === database);
  const hasBucket = existing.r2.includes(bucket);
  const vars: Record<string, string> = {};
  if (hosting.access_team) vars.ACCESS_TEAM = hosting.access_team;
  if (hosting.access_aud) vars.ACCESS_AUD = hosting.access_aud;
  if (opts.public) vars.PUBLIC = 'true';
  if (opts.signingKeys?.length) vars.SIGNING_KEYS = JSON.stringify(opts.signingKeys);
  if (hosting.oidc_repositories?.length) vars.OIDC_REPOSITORIES = JSON.stringify(hosting.oidc_repositories);
  if (hosting.roles) vars.ROLES = JSON.stringify(hosting.roles);

  const steps: string[][] = [];
  if (!hasBucket) steps.push(['r2', 'bucket', 'create', bucket]);
  if (!db) steps.push(['d1', 'create', database]);
  steps.push(['deploy', '--config', opts.configPath]);

  return {
    resources: [
      { type: 'r2', name: bucket, exists: hasBucket },
      { type: 'd1', name: database, exists: Boolean(db) },
      { type: 'worker', name: worker, exists: Boolean(existing.worker) },
    ],
    steps,
    commands: steps.map((args) => ['wrangler', ...args].map(shellQuote).join(' ')),
    wranglerConfig: {
      name: worker,
      main: opts.main,
      compatibility_date: opts.compatibilityDate ?? COMPATIBILITY_DATE,
      compatibility_flags: ['nodejs_compat'],
      assets: {
        directory: opts.assetsDir,
        binding: 'ASSETS',
        not_found_handling: 'single-page-application',
        run_worker_first: WORKER_FIRST_ROUTES,
      },
      r2_buckets: [{ binding: 'STORE', bucket_name: bucket }],
      d1_databases: [{ binding: 'DB', database_name: database, database_id: db?.uuid ?? PENDING_ID }],
      vars,
      triggers: { crons: ['* * * * *'] },
    },
  };
}

export function renderConfig(config: WranglerConfig): string {
  const header = '// Generated by `iw deploy`. Do not edit: it is rewritten on every deploy.';
  return `${header}\n${JSON.stringify(config, null, 2)}\n`;
}

export function shellQuote(arg: string): string {
  return /^[\w@%+=:,./-]+$/.test(arg) ? arg : `'${arg.replaceAll("'", `'\\''`)}'`;
}
